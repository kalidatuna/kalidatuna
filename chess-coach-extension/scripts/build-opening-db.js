/*
 * Builds src/core/openings-db.js from the lichess chess-openings TSV files in
 * data/chess-openings/ (CC0). Positions are precomputed here so the extension
 * does not have to replay thousands of lines with chess.js on every page load.
 *
 *   node scripts/build-opening-db.js
 */
const fs = require('fs');
const path = require('path');
require('../vendor/chess.js');
require('../src/core/opening-book.js'); // for the shared position-key hash
const { Chess } = globalThis.ChessJS;
const { positionKey } = globalThis.ChessCoach;

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data', 'chess-openings');
const OUT = path.join(ROOT, 'src', 'core', 'openings-db.js');


const positions = [];
const index = new Map();
const edges = new Map(); // "from|san" -> to
const lines = [];

function pos(key) {
  if (!index.has(key)) {
    index.set(key, positions.length);
    positions.push(key);
  }
  return index.get(key);
}

pos(positionKey(new Chess().fen()));
for (const f of ['a', 'b', 'c', 'd', 'e']) {
  const rows = fs.readFileSync(path.join(DATA, f + '.tsv'), 'utf8').trim().split('\n').slice(1);
  for (const row of rows) {
    const [eco, name, pgn] = row.split('\t');
    const sans = pgn.replace(/\d+\.(\.\.)?/g, ' ').trim().split(/\s+/);
    const chess = new Chess();
    let from = 0;
    for (const san of sans) {
      const mv = chess.move(san);
      const to = pos(positionKey(chess.fen()));
      edges.set(from + '|' + mv.san, to);
      from = to;
    }
    lines.push([eco, name, chess.history().join(' ')]);
  }
}

const edgeList = [...edges].map(([k, to]) => {
  const [from, san] = k.split('|');
  return [Number(from), san, to];
});

const body = `/* Generated by scripts/build-opening-db.js from the lichess chess-openings
 * data set (CC0, see data/chess-openings/LICENSE.txt). Do not edit by hand. */
(function (root) {
  const CC = (root.ChessCoach = root.ChessCoach || {});
  CC.OPENING_DB = ${JSON.stringify({ positions, edges: edgeList, lines })};
})(globalThis);
`;
fs.writeFileSync(OUT, body);
console.log(`${lines.length} lines, ${positions.length} positions, ${edgeList.length} moves -> ${path.relative(ROOT, OUT)} (${Math.round(body.length / 1024)} KB)`);
